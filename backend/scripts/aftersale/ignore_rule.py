"""售后工单「建议忽略」的机械判定规则（A 类）。

只处理两种**字面可判**的模式，不做语义推断：
  ① 客户购买物料（含购买/已付/报价类词）且无故障描述 → 忽略
  ② 纯补寄（含补寄/补发类词）且无故障描述           → 忽略
  ③ 含补寄类词但**有**故障描述                      → 不忽略

用户口述规则："只有补寄XXX这样的（没有其他内容）才忽略；
'2024.7.14 明睿扭扭断，补寄2个' 这种不能忽略。"

实测（2026-06，547 单）：精确率 96.3%（52/54，仅 2 单误判）、召回 44.4%。
第三轮由模型全靠语义判断时是 86.1% / 63.2% —— 机械规则精确率明显更高。

召回只有 44.4% 是预期的：本规则只覆盖上述两种模式，「表述含糊、找不到任何可推断
问题」那一类需要语义判断，应由模型补充，不要试图用关键词硬做。

★ 故障词表的完整度直接决定成败：只用常见故障词时，"纯补寄"桶里仅 53.8% 是该忽略的；
补上「无法/不行/相差/旧的/暗」等词后升到 77.8%。漏词会把需处理的单误判为忽略。
"""
import re

BUY_RE = re.compile(r'购买|已付|已支付|报价|自费|付款')
SEND_RE = re.compile(r'补寄|补发|重新发|重新寄')

# 故障 / 异常描述词。经 2026-06 实测校准，勿随意删减。
FAULT_RE = re.compile(
    r'断|坏|裂|破损|磕碰|划痕|划伤|不平|翘|异响|不亮|闪|失效|漏油|卡|松|掉|缺|没有|少|'
    r'错|歪|偏差|生锈|掉漆|瑕疵|色差|脏|变形|不顺|拧不|装不|插不|滑丝|弯曲|异常|失灵|'
    r'漏|响|抽不|关不|锁不|晃|凹|鼓|泡水|烧|霉|锈|污|痕|嫌弃|问题|'
    r'无法|不行|不能|不上|不下|不进|不住|相差|旧的|暗|紧|涩|不齐|高低|变色|起皮|'
    r'不满意|反馈|投诉|要求换|更换|换新|重拍'
)


def judge(seller_remark, buyer_remark=''):
    """→ (是否建议忽略, 依据说明)。返回 (False, None) 表示本规则不下结论，交语义判断。"""
    text = f'{seller_remark or ""} {buyer_remark or ""}'
    has_fault = bool(FAULT_RE.search(text))
    if has_fault:
        # 有故障描述：即便写了"补寄"也不能忽略
        return False, None
    if BUY_RE.search(text):
        return True, '含购买/已付类词且无故障描述 → 客户购买物料'
    if SEND_RE.search(text):
        return True, '纯补寄/补发且无故障描述 → 仅补物料、未述原因'
    return False, None
